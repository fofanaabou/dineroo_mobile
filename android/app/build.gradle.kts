// Read LOCAL key.properties file
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

// Read or create version.properties file
val versionPropsFile = file("version.properties")
val versionProps = Properties()

if (versionPropsFile.exists()) {
    versionProps.load(FileInputStream(versionPropsFile))
} else {
    versionProps["VERSION_CODE"] = "1"
    versionProps["VERSION_NAME"] = "1.0.0"
    versionProps.store(versionPropsFile.writer(), null)
}

// Read version values
val versionCodeValue = versionProps["VERSION_CODE"].toString().toInt()
val versionNameValue = versionProps["VERSION_NAME"].toString()

